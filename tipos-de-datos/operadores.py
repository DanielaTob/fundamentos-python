# Operadores aritmeticos 

x = 5 
y = 10

# Suma +
print("Suma",  x + y)

# Resta - 
print("Resta", x - y)

# Multiplicación * 
print("Multiplicación", x * y)

# División / (siempre nos devuelve un float)
print("División", y / x)

# Modulo % (resto de una división)
print("Modulo", y % x)

# Potencia ** 
print("Potencia", y ** x) # 10 * 10 * 10 * 10 * 10

# División Entera // 
print("División Entera", y // x )

par = 8
print(par % 2 == 0)

par = 7
print(par % 2 == 0)

